"""Core interfaces. Everything in the system is written against these two protocols.

The whole reliability argument rests on one property: StrategyEngine never knows
which mode it is running in. It pulls bars from a DataFeed and pushes orders into
a Broker. Backtest, paper and live differ only in which implementations get wired
in at startup.

    backtest -> HistoricalFeed + SimulatedBroker
    paper    -> LiveFeed       + SimulatedBroker
    live     -> LiveFeed       + UpstoxBroker

If you ever find yourself writing `if mode == "backtest"` inside engine or
strategy code, the seam has leaked and the modes will drift apart.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal
from enum import Enum
from typing import Iterator, Protocol, runtime_checkable


class Side(str, Enum):
    BUY = "BUY"
    SELL = "SELL"


class OrderType(str, Enum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"
    SL = "SL"
    SL_M = "SL_M"


class OrderStatus(str, Enum):
    PENDING = "PENDING"
    OPEN = "OPEN"
    FILLED = "FILLED"
    PARTIAL = "PARTIAL"
    CANCELLED = "CANCELLED"
    REJECTED = "REJECTED"


@dataclass(frozen=True, slots=True)
class Bar:
    """One OHLCV candle. Immutable so nothing downstream can rewrite history."""

    symbol: str
    timestamp: datetime  # bar OPEN time, timezone-aware, Asia/Kolkata
    open: Decimal
    high: Decimal
    low: Decimal
    close: Decimal
    volume: int
    oi: int | None = None  # open interest, F&O only


@dataclass(frozen=True, slots=True)
class Order:
    """An order request. `client_tag` is generated by us and must be unique.

    Idempotency depends on it: after a disconnect we reconcile by asking the
    broker which of our tags it already knows about, rather than re-sending
    blind and risking a double fill.
    """

    client_tag: str
    symbol: str
    side: Side
    quantity: int  # in units, not lots — lot conversion happens before this
    order_type: OrderType
    price: Decimal | None = None  # required for LIMIT / SL
    trigger_price: Decimal | None = None  # required for SL / SL_M
    strategy_id: str | None = None
    leg_id: str | None = None


@dataclass(frozen=True, slots=True)
class Fill:
    client_tag: str
    broker_order_id: str
    symbol: str
    side: Side
    quantity: int
    price: Decimal
    timestamp: datetime
    fees: Decimal  # all-in: brokerage + STT + exchange + GST + stamp duty
    status: OrderStatus


@dataclass(frozen=True, slots=True)
class Position:
    symbol: str
    quantity: int  # signed: negative is short
    average_price: Decimal
    last_price: Decimal
    realized_pnl: Decimal
    unrealized_pnl: Decimal


@runtime_checkable
class DataFeed(Protocol):
    """Source of bars. Hands out exactly one bar at a time, in order.

    The one-bar-at-a-time contract is what makes lookahead structurally
    impossible rather than merely discouraged — strategy code is never given a
    handle it could use to peek forward.
    """

    def stream(self) -> Iterator[Bar]:
        """Yield bars in chronological order until the feed is exhausted.

        Historical feeds terminate. Live feeds block until the next bar closes
        and only terminate on shutdown.
        """
        ...

    def warmup(self, symbol: str, bars: int) -> list[Bar]:
        """Bars strictly BEFORE the stream's first bar, for indicator priming.

        An EMA(20) needs history to be meaningful. Without this, the first
        20 bars of every backtest produce garbage signals — and, worse, live
        trading would produce different garbage than the backtest did.
        """
        ...


@runtime_checkable
class Broker(Protocol):
    """Destination for orders. Simulated in backtest and paper, real in live."""

    def place(self, order: Order) -> Fill | None:
        """Submit an order. Returns a Fill if immediately filled, else None.

        Implementations must be idempotent on `client_tag`: submitting the same
        tag twice never produces two orders.
        """
        ...

    def cancel(self, client_tag: str) -> bool: ...

    def positions(self) -> list[Position]:
        """Current positions AS THE BROKER SEES THEM.

        For live this is a fresh API call, not a cached local view. Reconciliation
        is only meaningful against the broker's own truth.
        """
        ...

    def reconcile(self) -> bool:
        """Compare broker state against internal state after any disconnect.

        Returns True only if they agree. The engine must refuse to trade on
        False — a mismatch means we do not know what we own, and acting on a
        guess is how accounts get destroyed.
        """
        ...
